-- Project Management System (PMS)
-- Proposed logical relational schema for PostgreSQL.
-- Review/align with Django models and migrations before running in a shared database.
-- Password values must be encoded hashes; never store plaintext passwords.

BEGIN;

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(150) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED','ACTIVE','ON_HOLD','COMPLETED','ARCHIVED')),
    start_date DATE,
    due_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (start_date IS NULL OR due_date IS NULL OR due_date >= start_date)
);

CREATE TABLE project_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    project_role VARCHAR(30) NOT NULL
        CHECK (project_role IN ('PROJECT_MANAGER','TEAM_MEMBER')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (project_id, user_id)
);

CREATE TABLE workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (project_id, name),
    UNIQUE (id, project_id)
);
CREATE UNIQUE INDEX ux_workflows_one_default_per_project
    ON workflows(project_id) WHERE is_default = TRUE;

CREATE TABLE workflow_states (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    sequence_order SMALLINT NOT NULL CHECK (sequence_order >= 0),
    category VARCHAR(20) NOT NULL DEFAULT 'TODO'
        CHECK (category IN ('TODO','IN_PROGRESS','DONE')),
    is_initial BOOLEAN NOT NULL DEFAULT FALSE,
    is_terminal BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (workflow_id, name),
    UNIQUE (workflow_id, sequence_order),
    UNIQUE (id, workflow_id)
);
CREATE UNIQUE INDEX ux_workflow_one_initial_state
    ON workflow_states(workflow_id) WHERE is_initial = TRUE;

CREATE TABLE workflow_transitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    from_state_id BIGINT NOT NULL,
    to_state_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (from_state_id, workflow_id)
        REFERENCES workflow_states(id, workflow_id) ON DELETE CASCADE,
    FOREIGN KEY (to_state_id, workflow_id)
        REFERENCES workflow_states(id, workflow_id) ON DELETE CASCADE,
    CHECK (from_state_id <> to_state_id),
    UNIQUE (workflow_id, from_state_id, to_state_id)
);

CREATE TABLE sprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    goal TEXT,
    start_date DATE,
    end_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED','ACTIVE','COMPLETED')),
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date),
    UNIQUE (project_id, name),
    UNIQUE (id, project_id)
);

CREATE TABLE milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(160) NOT NULL,
    description TEXT,
    target_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED','IN_PROGRESS','COMPLETED','CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (project_id, name),
    UNIQUE (id, project_id)
);

CREATE TABLE tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    workflow_state_id BIGINT NOT NULL REFERENCES workflow_states(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    assignee_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    sprint_id BIGINT,
    milestone_id BIGINT,
    title VARCHAR(250) NOT NULL,
    description TEXT,
    task_type VARCHAR(20) NOT NULL DEFAULT 'TASK'
        CHECK (task_type IN ('TASK','BUG','STORY','ISSUE')),
    priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM'
        CHECK (priority IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    estimate_points SMALLINT CHECK (estimate_points IS NULL OR estimate_points >= 0),
    estimated_hours NUMERIC(8,2) CHECK (estimated_hours IS NULL OR estimated_hours >= 0),
    actual_hours NUMERIC(8,2) CHECK (actual_hours IS NULL OR actual_hours >= 0),
    due_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    FOREIGN KEY (sprint_id, project_id)
        REFERENCES sprints(id, project_id) ON DELETE RESTRICT,
    FOREIGN KEY (milestone_id, project_id)
        REFERENCES milestones(id, project_id) ON DELETE RESTRICT,
    UNIQUE (id, project_id)
);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    body TEXT NOT NULL CHECK (length(trim(body)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    uploaded_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    original_file_name VARCHAR(255) NOT NULL,
    storage_key TEXT NOT NULL,
    content_type VARCHAR(150),
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    task_id BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
    notification_type VARCHAR(80) NOT NULL,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ,
    CHECK (read_at IS NULL OR is_read = TRUE)
);

CREATE TABLE activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    project_id BIGINT REFERENCES projects(id) ON DELETE SET NULL,
    task_id BIGINT REFERENCES tasks(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Query indexes for the most common project/task/dashboard/notification views.
CREATE INDEX ix_project_members_user ON project_members(user_id);
CREATE INDEX ix_tasks_project_state ON tasks(project_id, workflow_state_id);
CREATE INDEX ix_tasks_assignee ON tasks(assignee_id);
CREATE INDEX ix_tasks_sprint ON tasks(sprint_id);
CREATE INDEX ix_tasks_milestone ON tasks(milestone_id);
CREATE INDEX ix_comments_task_created ON comments(task_id, created_at);
CREATE INDEX ix_notifications_recipient_read ON notifications(recipient_id, is_read, created_at DESC);
CREATE INDEX ix_activity_project_created ON activity_logs(project_id, created_at DESC);
CREATE INDEX ix_activity_task_created ON activity_logs(task_id, created_at DESC);

COMMIT;

-- Application-level integrity checks to implement in Django/service validation:
-- 1. A task's workflow_state must belong to a workflow for the same project as the task.
-- 2. An assignee must be an active member of the task's project (unless Admin policy permits otherwise).
-- 3. The task creator must have permission to create tasks in the project.
-- 4. Only configured workflow_transitions are permitted when changing a task's state.
-- 5. Updates to updated_at should be handled via Django auto_now or an approved DB trigger.
-- 6. A project owner should also have membership/management access to that project.
